def apply_category_ru(category: Category) -> bool:
    if category.name_ru:
        return False
    ru = CATEGORY_NAME_RU.get(category.name)
    if not ru:
        return False
    category.name_ru = ru
    category.save(update_fields=["name_ru"])
    return True


def apply_product_ru(product: Product) -> bool:
    fields: list[str] = []
    cat_name = product.category.name if product.category_id else ""
    if not product.name_ru and product.name:
        product.name_ru = _product_name_ru(product.name)
        fields.append("name_ru")
    if not product.short_description_ru and product.short_description:
        product.short_description_ru = _short_desc_ru(product.short_description, cat_name)
        fields.append("short_description_ru")
    if not product.description_ru and product.description:
        product.description_ru = _description_ru(product.description, cat_name)
        fields.append("description_ru")
    if not fields:
        return False
    product.save(update_fields=fields)
    return True


def apply_highlight_ru(point: HighlightPoint) -> bool:
    pair = HIGHLIGHT_RU.get(point.title)
    fields: list[str] = []
    if pair and not point.title_ru:
        point.title_ru = pair[0]
        fields.append("title_ru")
    if not point.text_ru:
        text_ru = HIGHLIGHT_TEXT_RU.get(point.text, "")
        if not text_ru and pair:
            text_ru = pair[1]
        if text_ru:
            point.text_ru = text_ru
            fields.append("text_ru")
    if not fields:
        return False
    point.save(update_fields=fields)
    return True


def apply_review_ru(review: Review) -> bool:
    pair = REVIEW_RU.get(review.name)
    if not pair:
        return False
    city_ru, text_ru = pair
    fields: list[str] = []
    if not review.city_ru and city_ru:
        review.city_ru = city_ru
        fields.append("city_ru")
    if not review.text_ru and text_ru:
        review.text_ru = text_ru
        fields.append("text_ru")
    if not fields:
        return False
    review.save(update_fields=fields)
    return True


