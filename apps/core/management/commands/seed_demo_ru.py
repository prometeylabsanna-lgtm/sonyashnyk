def _product_name_ru(name: str) -> str:
    if name in PRODUCT_NAME_RU:
        return PRODUCT_NAME_RU[name]
    match = MARK_SUFFIX_RE.match(name)
    if match:
        base, mark = match.group(1), match.group(2)
        base_ru = CATEGORY_NAME_RU.get(base, base)
        mark_ru = MARK_RU.get(mark, mark)
        return f"{base_ru} «{mark_ru}»"
    return name


def _short_desc_ru(text: str, category_name: str) -> str:
    if not text:
        return ""
    _build_short_desc_ru_flat()
    if text in SHORT_DESC_RU:
        return SHORT_DESC_RU[text]
    if text in DEMO_SHORT_FALLBACK_RU:
        return DEMO_SHORT_FALLBACK_RU[text]
    try:
        from apps.core.management.commands.seed_demo import SHORT_DESCS

        ua_list = SHORT_DESCS.get(category_name, [])
        ru_list = SHORT_DESC_RU_BY_CATEGORY.get(category_name, [])
        if text in ua_list and ru_list:
            idx = ua_list.index(text)
            if idx < len(ru_list):
                return ru_list[idx]
    except ImportError:
        pass
    return GENERIC_SHORT_DESC_RU


